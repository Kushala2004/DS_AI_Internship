import numpy as np
sales=np.array([[40,50,60],[30,70,60]])
print(sales)
print(sales.reshape(3,2))
print("mean:",np.mean(sales))
r=np.mean(sales,axis=0)
print(r)
r1=np.mean(sales,axis=1)
print(r1)
print("median:",np.median(sales))
r2=np.median(sales,axis=0)
print(r2)
r3=np.median(sales,axis=1)
print(r3)
print("var:",np.var(sales))
r4=np.var(sales,axis=0)
print(r4)
r5=np.var(sales,axis=1)
print(r5)
